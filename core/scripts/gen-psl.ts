// Generates the public suffix rules (review V3-S2) for both cores from a downloaded Public Suffix List:
//   core/src/autofill/psl-rules.ts and android/core/src/main/resources/.../public_suffix_rules.txt
// Update: download https://publicsuffix.org/list/public_suffix_list.dat, then
//   npm run gen-psl -w core -- path/to/public_suffix_list.dat
// Rules are converted to ASCII (punycode) because both cores compare ASCII hosts. ICANN and private sections are both
// kept: a private suffix (github.io, blogspot.com) also separates owners.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const source = process.argv[2];
if (!source) throw new Error("usage: gen-psl <public_suffix_list.dat>");
const raw = readFileSync(source, "utf8");

function ascii(rule: string): string {
  const prefix = rule.startsWith("!") ? "!" : rule.startsWith("*.") ? "*." : "";
  const name = domainToASCII(rule.slice(prefix.length));
  if (name === "") throw new Error(`bad rule: ${rule}`);
  return prefix + name;
}

const rules = raw
  .split("\n")
  .map((line) => line.trim().split(/\s/)[0]!)
  .filter((line) => line !== "" && !line.startsWith("//"))
  .map(ascii);
const unique = [...new Set(rules)].sort();
const sha = createHash("sha256").update(raw).digest("hex");
const header = [
  "Generated by core/scripts/gen-psl.ts from https://publicsuffix.org/list/public_suffix_list.dat",
  `sha256 of the source: ${sha}`,
  "The Public Suffix List is subject to the Mozilla Public License, v. 2.0 (https://mozilla.org/MPL/2.0/).",
];

const root = new URL("../../", import.meta.url);
writeFileSync(
  new URL("core/src/autofill/psl-rules.ts", root),
  `${header.map((h) => `// ${h}`).join("\n")}\n// Do not edit by hand.\n\n/** Public suffix rules, one per line ("*." wildcard, "!" exception), ASCII. */\nexport const PSL_RULES = ${JSON.stringify(unique.join("\n"))};\n`,
);
writeFileSync(
  new URL(
    "android/core/src/main/resources/io/github/sheking94/passholder/core/autofill/public_suffix_rules.txt",
    root,
  ),
  `${header.map((h) => `// ${h}`).join("\n")}\n${unique.join("\n")}\n`,
);
console.log(`${unique.length} rules`);
